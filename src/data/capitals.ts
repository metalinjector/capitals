export function filterCapitals(region: RegionId): Capital[] {
  if (region === "all") return capitals;
  if (region === "school") return capitals.filter((c) => c.school);
  if (region === "micro") return capitals.filter((c) => c.micro);
  return capitals.filter((c) => c.region === region);
}

export function byId(id: string) {
  return capitals.find((c) => c.id === id);
}
